-- Spike filter for Markdown -> DOCX: maps semantic nodes to named Word styles.

local function style_attr(name) return pandoc.Attr('', {}, { ['custom-style'] = name }) end

local function span(el, name) return pandoc.Span(el.content, style_attr(name)) end

function Strong(el) return span(el, 'Strong') end
function Emph(el) return span(el, 'Emphasis') end

local function wrap_leading(item, name)
  local out = {}
  for i, block in ipairs(item) do
    if block.t == 'Plain' or block.t == 'Para' then
      out[i] = pandoc.Div({ block }, style_attr(name))
    else
      out[i] = block
    end
  end
  return out
end

local function map_items(el, name)
  for i, item in ipairs(el.content) do el.content[i] = wrap_leading(item, name) end
  return el
end

function BulletList(el) return map_items(el, 'List Bullet') end
function OrderedList(el) return map_items(el, 'List Number') end

local function normal(blocks)
  local out = {}
  for i, block in ipairs(blocks) do
    if block.t == 'Plain' or block.t == 'Para' then
      out[i] = pandoc.Div({ block }, style_attr('Normal'))
    else
      out[i] = block
    end
  end
  return out
end

local function map_cell_blocks(el)
  -- The docx writer forces its "Compact" style on Plain blocks in cells.
  local block = el.t == 'Plain' and pandoc.Para(el.content) or el
  return pandoc.Div({ block }, style_attr('Normal'))
end

-- One table style for every table until the stylesheet defines several.
function Table(tbl)
  tbl = tbl:walk({ Plain = map_cell_blocks, Para = map_cell_blocks })
  tbl.attr = pandoc.Attr('', {}, { ['custom-style'] = 'TableGrid' })
  return tbl
end

function Pandoc(doc)
  doc.blocks = normal(doc.blocks)
  doc.meta = pandoc.Meta({}) -- the title block is derived from project metadata, not generated by the writer
  return doc
end
